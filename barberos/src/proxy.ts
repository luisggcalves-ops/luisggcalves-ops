import { NextResponse, type NextRequest } from "next/server";
import { resolveBaseUrl } from "@/lib/deploy-env";

/**
 * Content-Security-Policy with a fresh nonce per request. Next.js reads the nonce
 * from the request's CSP header and puts it on its own scripts, so no inline
 * script runs unless it came from us. Styles allow inline attributes, because the
 * calendar positions blocks with them. Inline *scripts* stay forbidden.
 */
export function proxy(request: NextRequest) {
  const nonce = Buffer.from(crypto.randomUUID()).toString("base64");
  const isDev = process.env.NODE_ENV === "development";
  const https = (resolveBaseUrl(process.env) ?? "").startsWith("https://");
  const csp = [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${isDev ? " 'unsafe-eval'" : ""}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' blob: data:",
    "font-src 'self' data:",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(https ? ["upgrade-insecure-requests"] : []),
  ].join("; ");

  const requestHeaders = new Headers(request.headers);
  requestHeaders.set("x-nonce", nonce);
  requestHeaders.set("Content-Security-Policy", csp);
  const response = NextResponse.next({ request: { headers: requestHeaders } });
  response.headers.set("Content-Security-Policy", csp);
  return response;
}

export const config = {
  matcher: [
    {
      // Pages only. Skip API routes, static files and link prefetches.
      source: "/((?!api|_next/static|_next/image|favicon.ico|.*\\.ics$).*)",
      missing: [
        { type: "header", key: "next-router-prefetch" },
        { type: "header", key: "purpose", value: "prefetch" },
      ],
    },
  ],
};
